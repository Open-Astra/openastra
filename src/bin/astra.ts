// ── Resolve astra.yml ───────────────────────────────────────────────

async function resolveAstraYml(): Promise<void> {
  // 1. Check cwd
  try {
    await access(join(process.cwd(), "astra.yml"));
    info("Using astra.yml from current directory");
    return;
  } catch { /* not in cwd */ }

  // 2. Check ~/.astra/astra.yml
  try {
    await access(DEFAULT_ASTRA_YML_PATH);
    process.env.ASTRA_CONFIG_PATH = DEFAULT_ASTRA_YML_PATH;
    info("Using astra.yml from ~/.astra/");
    return;
  } catch { /* not there either */ }

  // 3. No config file — gateway will start without agent team
  warn("No astra.yml found. Gateway will start with no agents configured.");
  warn("Create one with: npx astra setup");
}

// ── Run ─────────────────────────────────────────────────────────────

main().catch((err) => {
  console.error(`\n${RED}${BOLD}Fatal error:${RESET}`, err instanceof Error ? err.message : err);
  process.exit(1);
});
