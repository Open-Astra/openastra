import { join } from "node:path";

// ── Code Generator ─────────────────────────────────────────────────
// `astra scaffold <type> <name>` — generates boilerplate for common
// project components:
//   - skill   — skill definition + test
//   - agent   — agent config entry
//   - route   — Express route handler + test
//   - plugin  — gateway plugin skeleton

const BOLD = "\x1b[1m";
const RESET = "\x1b[0m";
const DIM = "\x1b[2m";
const GREEN = "\x1b[32m";
const CYAN = "\x1b[36m";
const RED = "\x1b[31m";
type ScaffoldType = "skill" | "route" | "plugin";

