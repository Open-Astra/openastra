// ── Helpers ────────────────────────────────────────────────────────

function toCamelCase(str: string): string {
  return str.replace(/[-_](.)/g, (_, c) => c.toUpperCase());
}

function pascalCase(str: string): string {
  const camel = toCamelCase(str);
  return camel.charAt(0).toUpperCase() + camel.slice(1);
}

async function ensureDir(dir: string): Promise<void> {
  try {
    await access(dir);
  } catch {
    await mkdir(dir, { recursive: true });
  }
}

// ── Main ───────────────────────────────────────────────────────────

export async function runScaffold(): Promise<void> {
  const args = process.argv.slice(2).filter((a: string) => a !== "scaffold");
  const type = args[0] as ScaffoldType | undefined;
  const name = args[1];

  if (!type || !name) {
    printUsage();
    process.exit(1);
  }

  if (!["skill", "route", "plugin"].includes(type!)) {
    console.log(`${RED}Unknown scaffold type: ${type}${RESET}`);
    printUsage();
    process.exit(1);
  }

  // Validate name
  if (!/^[a-z][a-z0-9_-]*$/.test(name)) {
    console.log(`${RED}Invalid name: "${name}" — use lowercase letters, numbers, hyphens, underscores${RESET}`);
    process.exit(1);
  }

  const camelName = toCamelCase(name);
  const rootDir = process.cwd();
  const created: string[] = [];

  console.log(`\n${BOLD}  Scaffolding ${type}: ${CYAN}${name}${RESET}\n`);

  switch (type) {
    case "skill": {
      const skillDir = join(rootDir, "src/skills/definitions", name);
      const testDir = join(rootDir, "tests/skills");

      await ensureDir(skillDir);
      await ensureDir(testDir);

      await writeFile(join(skillDir, "index.ts"), skillTemplate(name, camelName));
      created.push(`src/skills/definitions/${name}/index.ts`);

      await writeFile(join(testDir, `${name}.test.ts`), skillTestTemplate(name));
      created.push(`tests/skills/${name}.test.ts`);
      break;
    }

    case "route": {
      const routeDir = join(rootDir, "src/gateway/routes");
      const testDir = join(rootDir, "tests/routes");

      await ensureDir(testDir);

      await writeFile(join(routeDir, `${name}.ts`), routeTemplate(name, camelName));
      created.push(`src/gateway/routes/${name}.ts`);

      await writeFile(join(testDir, `${name}.test.ts`), routeTestTemplate(name));
      created.push(`tests/routes/${name}.test.ts`);
      break;
    }

    case "plugin": {
      const pluginDir = join(rootDir, "src/plugins/core", name);

      await ensureDir(pluginDir);

      await writeFile(join(pluginDir, "index.ts"), pluginTemplate(name));
      created.push(`src/plugins/core/${name}/index.ts`);
      break;
    }
  }

  // Print summary
  for (const file of created) {
    console.log(`  ${GREEN}✓${RESET} Created ${file}`);
  }

  console.log(`\n${DIM}  Next steps:${RESET}`);
  switch (type) {
    case "skill":
      console.log(`  1. Implement skill logic in src/skills/definitions/${name}/index.ts`);
      console.log(`  2. Register in src/skills/registry.ts (or use hot-reload)`);
      console.log(`  3. Run tests: npx vitest tests/skills/${name}.test.ts`);
      break;
    case "route":
      console.log(`  1. Implement route handlers in src/gateway/routes/${name}.ts`);
      console.log(`  2. Mount in src/gateway/index.ts: api.use("/${name}", create${pascalCase(name)}Router())`);
      console.log(`  3. Run tests: npx vitest tests/routes/${name}.test.ts`);
      break;
    case "plugin":
      console.log(`  1. Implement plugin logic in src/plugins/core/${name}/index.ts`);
      console.log(`  2. Register in src/plugins/loader.ts or use hot-reload`);
      break;
  }
  console.log();
}

function printUsage(): void {
  console.log(`
${BOLD}Usage:${RESET}
  npx astra scaffold <type> <name>

${BOLD}Types:${RESET}
  ${CYAN}skill${RESET}    Create a skill definition + test
  ${CYAN}route${RESET}    Create an Express route handler + test
  ${CYAN}plugin${RESET}   Create a gateway plugin skeleton

${BOLD}Examples:${RESET}
  ${DIM}$${RESET} npx astra scaffold skill weather-alerts
  ${DIM}$${RESET} npx astra scaffold route user-preferences
  ${DIM}$${RESET} npx astra scaffold plugin analytics-tracker
`);
}
