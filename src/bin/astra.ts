#!/usr/bin/env node

// ── Astra CLI Entry Point ───────────────────────────────────────────
// Zero-config launcher: npx astra
//
// Subcommands:
//   (none) / start  — launch gateway with auto-managed Docker services
//   chat             — launch standalone CLI chat
//   setup            — run onboarding wizard (re-run to reconfigure)
//   stop             — stop Docker services
//   status           — show service status
//   reset            — wipe config + Docker containers + volumes

import { access } from "node:fs/promises";
import { join } from "node:path";
import {
  configExists, loadConfig, deleteConfig, injectEnv,
  DEFAULT_ASTRA_YML_PATH,
} from "./config.js";
import {
  checkDocker, startServices, stopServices, removeServices,
  waitForHealthy, getServiceStatus,
} from "./docker.js";
import { runOnboarding } from "./onboard.js";
import {
  BOLD, RESET, DIM, CYAN, GREEN, RED, YELLOW,
  section, success, error as showError, info, warn,
  createRL, askYesNo,
} from "./tui.js";

// ── Subcommand Routing ──────────────────────────────────────────────

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  const command = args[0] || "start";

  switch (command) {
    case "start":
      return cmdStart();
    case "chat":
      return cmdChat();
    case "costs":
      return cmdCosts();
    case "dev":
      return cmdDev();
    case "doctor":
      return cmdDoctor();
    case "heartbeat":
      return cmdHeartbeat();
    case "setup":
      return cmdSetup();
    case "tunnel":
      return cmdTunnel();
    case "scaffold":
      return cmdScaffold();
    case "replay":
      return cmdReplay();
    case "bench":
      return cmdBench();
    case "migrate":
      return cmdMigrate();
    case "stop":
      return cmdStop();
    case "status":
      return cmdStatus();
    case "reset":
      return cmdReset();
    case "--help":
    case "-h":
    case "help":
      return cmdHelp();
    default:
      console.log(`${RED}Unknown command: ${command}${RESET}`);
      cmdHelp();
      process.exit(1);
  }
}

// ── start (default) ─────────────────────────────────────────────────

async function cmdStart(): Promise<void> {
  // 1. Config — run onboarding if first time
  let config;
  if (await configExists()) {
    config = await loadConfig();
    info("Loaded config from ~/.astra/config.json");
  } else {
    config = await runOnboarding();
  }

  // 2. Docker check
  const docker = await checkDocker();
  if (!docker.ok) {
    showError(docker.error!);
    process.exit(1);
  }

  // 3. Start services
  section("Starting Services");
  info("Starting PostgreSQL and Typesense...");
  await startServices(config);
  success("Containers started");

  // 4. Wait for healthy
  info("Waiting for services to be ready...");
  try {
    await waitForHealthy(config);
  } catch (err) {
    showError(err instanceof Error ? err.message : String(err));
    showError("Services failed to become healthy. Check 'docker logs astra-postgres' or 'docker logs astra-typesense'.");
    process.exit(1);
  }
  success("PostgreSQL is ready");
  success("Typesense is ready");

  // 5. Inject env
  injectEnv(config);

  // 6. Resolve astra.yml — cwd > ~/.astra/ > (already generated by onboarding)
  await resolveAstraYml();

  // 7. Start gateway via dynamic import
  section("Starting Gateway");
  info(`Launching on http://localhost:${config.gatewayPort}`);
  console.log();
  await import("../gateway/index.js");
}

