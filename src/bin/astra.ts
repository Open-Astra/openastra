// ── status ──────────────────────────────────────────────────────────

async function cmdStatus(): Promise<void> {
  const hasConfig = await configExists();

  section("Astra Status");

  // Config
  if (hasConfig) {
    const config = await loadConfig();
    success(`Config: ~/.astra/config.json`);
    info(`  Provider: ${config.defaultProvider}`);
    info(`  Gateway port: ${config.gatewayPort}`);
    info(`  Postgres port: ${config.pgPort}`);
    info(`  Typesense port: ${config.typesensePort}`);
  } else {
    warn("Not configured — run 'npx astra setup'");
    return;
  }

  // Docker
  const docker = await checkDocker();
  if (!docker.ok) {
    warn(`Docker: ${docker.error}`);
    return;
  }
  success("Docker: available");

  // Containers
  const status = await getServiceStatus();
  const fmt = (s: string) =>
    s === "running" ? `${GREEN}${s}${RESET}` :
    s === "stopped" ? `${YELLOW}${s}${RESET}` :
    `${DIM}${s}${RESET}`;

  console.log(`  PostgreSQL:  ${fmt(status.postgres)}`);
  console.log(`  Typesense:   ${fmt(status.typesense)}`);
}

// ── reset ───────────────────────────────────────────────────────────

async function cmdReset(): Promise<void> {
  const rl = createRL();
  const confirmed = await askYesNo(rl, `${RED}This will delete all Astra data (config, containers, volumes). Continue?${RESET}`, false);
  rl.close();

  if (!confirmed) {
    info("Cancelled.");
    return;
  }

  const docker = await checkDocker();
  if (docker.ok) {
    info("Removing Docker containers and volumes...");
    await removeServices();
    success("Docker resources removed");
  }

  info("Removing ~/.astra/ config...");
  await deleteConfig();
  success("Config removed");

  console.log(`\n  ${GREEN}Reset complete.${RESET} Run ${CYAN}npx astra${RESET} to start fresh.\n`);
}

